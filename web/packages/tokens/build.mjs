// Generates tokens.css (CSS variables, light + dark + RTL-aware Urdu type) and tokens.ts from tokens.json.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const t = JSON.parse(readFileSync(join(here, "tokens.json"), "utf8"));

const kebab = (s) => s.replace(/[A-Z]/g, (c) => "-" + c.toLowerCase());
const vars = (theme) => Object.entries(theme).map(([k, v]) => `  --uf-${kebab(k)}: ${v};`).join("\n");

const px = (n) => `${n}px`;
const common = [
  ...Object.entries(t.font.size).map(([k, v]) => `  --uf-font-size-${k}: ${px(v)};`),
  `  --uf-font-latin: ${t.font.latin};`,
  `  --uf-font-urdu: ${t.font.urdu};`,
  ...t.space.map((v, i) => `  --uf-space-${i}: ${px(v)};`),
  ...Object.entries(t.radius).map(([k, v]) => `  --uf-radius-${k}: ${px(v)};`),
  ...Object.entries(t.shadow).map(([k, v]) => `  --uf-shadow-${k}: ${v};`),
  ...Object.entries(t.gradients).map(([k, [a, b]]) => `  --uf-${kebab(k)}: linear-gradient(135deg, ${a}, ${b});`),
  `  --uf-kpi-tile-text: ${t.kpiTileText};`,
  `  --uf-touch-target: ${px(t.touchTarget)};`,
].join("\n");

const css = `/* GENERATED by build.mjs from tokens.json. Do not edit. */
:root {
${vars(t.themes.light)}
${common}
  color-scheme: light;
}

:root[data-theme="dark"] {
${vars(t.themes.dark)}
  color-scheme: dark;
}

@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
${vars(t.themes.dark).replace(/^/gm, "  ")}
    color-scheme: dark;
  }
}

body { font-family: var(--uf-font-latin); line-height: ${t.font.lineHeight}; color: var(--uf-text); background: var(--uf-bg); }
:lang(ur), [lang="ur"] { font-family: var(--uf-font-urdu); line-height: ${t.font.urduLineHeight}; font-size: ${t.font.urduScale}em; }
[dir="rtl"] { text-align: start; }
:focus-visible { outline: 3px solid var(--uf-focus-ring); outline-offset: 2px; }
`;

const ts = `// GENERATED by build.mjs from tokens.json. Do not edit.
export const tokens = ${JSON.stringify({ themes: t.themes, gradients: t.gradients, font: t.font, space: t.space, radius: t.radius, touchTarget: t.touchTarget }, null, 2)} as const;
export type ThemeName = keyof typeof tokens.themes;
`;

writeFileSync(join(here, "tokens.css"), css);
writeFileSync(join(here, "tokens.ts"), ts);
console.log("tokens built");
